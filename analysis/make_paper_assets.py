def nc_extra_assets(nc: dict) -> None:
    """Macros for the A-tier analyses: micro accuracy, response types, logit gaps, length CIs."""
    for k in MODELS:
        M = MACRO[k]
        mi = nc["micro_exact"][k]
        m(f"nc{M}MicroIn", pct(mi["in"]))
        m(f"nc{M}MicroOut", pct(mi["out"]))
        rt = nc["response_type"][k]
        m(f"rt{M}Visible", pct(rt["share_visible_reasoning"], 0))
        m(f"rt{M}AccVisible", pct(rt["acc_visible"]))
        m(f"rt{M}AccDirect", pct(rt["acc_direct"]))
        for rk, R in (("in", "In"), ("out", "Out")):
            lgv = nc["logit_gap"][k][rk]
            m(f"lg{M}{R}", f"{lgv['gap']:+.2f}".replace("-", "$-$"))
            m(f"lg{M}{R}Lo", f"{lgv['ci'][0]:+.2f}".replace("-", "$-$"))
            m(f"lg{M}{R}Hi", f"{lgv['ci'][1]:+.2f}".replace("-", "$-$"))
        sv = nc["sensitivity"]["exact_value"][k]
        m(f"val{M}In", pct(sv["in"]["all"]))
        m(f"val{M}Out", pct(sv["out"]["all"]))
    ci = nc["well_learned_ci"]
    m("wlGptMaxFloatLo", str(ci["gpt"]["max_Float_Float_Float"][0]))
    m("wlGptMaxFloatHi", str(ci["gpt"]["max_Float_Float_Float"][1]))
    m("wlClaudeCountLo", str(ci["claude"]["count_Integer_int_int"][0]))
    m("wlClaudeCountHi", str(ci["claude"]["count_Integer_int_int"][1]))


