"""Generate every Section 5 number, table, and data figure of the manuscript.

Inputs : analysis/out/nc_results.json, analysis/out/ctx_results.json
Outputs: paper/generated/results_macros.tex   (\\newcommand per reported number)
         paper/generated/tab_*.tex             (tables, \\input by main.tex)
         paper/figures/generated/fig*.pdf      (data figures)

The manuscript must not hard-code Section 5 numbers; check_manuscript.py enforces this.
"""

